class HairAnalyzer:
    L_EAR, R_EAR, NOSE, L_SH, R_SH, L_HIP = 3, 4, 0, 5, 6, 11

    @classmethod
    def analyze(cls, img_rgb, person, mask_entry):
        kp, conf = person["keypoints"], person["kp_conf"]
        x1, y1, x2, y2 = person["bbox"]

        def valid(i):
            return conf[i] > 0.25 and not (kp[i][0] == 0 and kp[i][1] == 0)

        if not valid(cls.NOSE):
            return {"color": "no detectado", "longitud": "no detectado"}

        # Región de cabello: banda sobre la cabeza + laterales, dentro del bbox
        head_top = y1
        eye_y = int(kp[cls.NOSE][1])
        band_bottom = eye_y
        hair_region = img_rgb[max(0, head_top):max(1, band_bottom), x1:x2]

        if mask_entry is not None:
            m = mask_entry["mask"][max(0, head_top):max(1, band_bottom), x1:x2]
            if m.shape[:2] == hair_region.shape[:2]:
                hair_region = hair_region[m.astype(bool)] if m.any() else hair_region.reshape(-1, 3)
            else:
                hair_region = hair_region.reshape(-1, 3)
        else:
            hair_region = hair_region.reshape(-1, 3)

        pixels = hair_region.reshape(-1, 3) if hair_region.ndim == 3 else hair_region
        # descarta píxeles muy claros (posible fondo) y muy oscuros (sombra dura)
        if len(pixels) > 20:
            lum = pixels.mean(axis=1)
            pixels = pixels[(lum > 10) & (lum < 250)]

        color_rgb = dominant_color(pixels, k=3)
        color_label = _closest_label(color_rgb, HAIR_COLOR_TABLE) if color_rgb is not None else "no detectado"

        # Longitud aproximada: ¿la máscara de persona se extiende angosta
        # (pelo) por debajo de la línea de hombros u orejas?
        longitud = "corto"
        if mask_entry is not None and valid(cls.L_SH) and valid(cls.R_SH):
            shoulder_y = int((kp[cls.L_SH][1] + kp[cls.R_SH][1]) / 2)
            ear_y = int(kp[cls.L_EAR][1]) if valid(cls.L_EAR) else eye_y
            mask = mask_entry["mask"]
            # ancho de la "cabeza+cuello" justo antes del hombro vs en la oreja
            def width_at(y):
                yy = int(np.clip(y, 0, mask.shape[0] - 1))
                row = mask[yy, x1:x2]
                xs = np.where(row > 0)[0]
                return (xs.max() - xs.min()) if len(xs) else 0
            w_ear = width_at(ear_y)
            w_neck = width_at(int((ear_y + shoulder_y) / 2))
            if w_neck > w_ear * 1.4:
                longitud = "largo (cubre hombros/cuello)"
            elif w_neck > w_ear * 1.1:
                longitud = "medio"

        return {"color": color_label, "longitud": longitud}


