class MultiModelSegmenter:
    def __init__(self, yolo_model="yolov8n-seg.pt"):
        self.yolo = YOLO(yolo_model) if HAS_YOLO else None
        self.mp_seg = None
        if HAS_MEDIAPIPE:
            try:
                self.mp_seg = mp.solutions.selfie_segmentation.SelfieSegmentation(model_selection=1)
            except (AttributeError, Exception) as e:
                print(f"[aviso] MediaPipe SelfieSegmentation no disponible ({e}); "
                      f"se sigue solo con YOLO-Seg.")
                self.mp_seg = None

    def _yolo_masks(self, img_bgr, conf):
        if self.yolo is None:
            return []
        h, w = img_bgr.shape[:2]
        results = self.yolo(img_bgr, conf=conf, classes=[0], verbose=False)[0]
        masks = []
        if results.masks is None:
            return []
        for mask_data, box in zip(results.masks.data, results.boxes):
            m = cv2.resize(mask_data.cpu().numpy(), (w, h))
            masks.append({"mask": (m > 0.5).astype(np.uint8),
                          "bbox": box.xyxy[0].cpu().numpy().astype(int)})
        return masks

    def _mediapipe_mask(self, img_bgr, bbox):
        """Fallback de segmentación por persona, útil si YOLO-seg falla
        (fondo complejo, pose extrema, recorte parcial)."""
        if self.mp_seg is None:
            return None
        x1, y1, x2, y2 = bbox
        h, w = img_bgr.shape[:2]
        x1, y1, x2, y2 = max(0, x1), max(0, y1), min(w, x2), min(h, y2)
        crop = img_bgr[y1:y2, x1:x2]
        if crop.size == 0:
            return None
        rgb = cv2.cvtColor(crop, cv2.COLOR_BGR2RGB)
        res = self.mp_seg.process(rgb)
        if res.segmentation_mask is None:
            return None
        full = np.zeros((h, w), dtype=np.uint8)
        full[y1:y2, x1:x2] = (res.segmentation_mask > 0.5).astype(np.uint8)
        return {"mask": full, "bbox": np.array([x1, y1, x2, y2])}

    def detect(self, img_bgr, people, conf=0.30):
        masks = self._yolo_masks(img_bgr, conf)
        matched = []
        for person in people:
            best = self._match(person, masks)
            if best is None:
                best = self._mediapipe_mask(img_bgr, person["bbox"])
            matched.append(best)
        return matched

    @staticmethod
    def _match(person, masks):
        if not masks:
            return None
        kp = person["keypoints"]
        valid_pts = kp[np.any(kp != 0, axis=1)]
        if len(valid_pts) == 0:
            return None
        center = valid_pts.mean(axis=0)
        best, best_d = None, float("inf")
        for m in masks:
            mx1, my1, mx2, my2 = m["bbox"]
            mc = np.array([(mx1 + mx2) / 2, (my1 + my2) / 2])
            d = np.linalg.norm(center - mc)
            if d < best_d:
                best, best_d = m, d
        return best


