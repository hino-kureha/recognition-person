class MultiModelPoseEstimator:
    """Ensambla YOLOv8-Pose con MediaPipe Pose para rellenar keypoints faltantes
    y estimar profundidad relativa (mejor detección de perfil / 3-4 / espalda)."""

    COCO_NAMES = ["nose", "l_eye", "r_eye", "l_ear", "r_ear",
                  "l_shoulder", "r_shoulder", "l_elbow", "r_elbow",
                  "l_wrist", "r_wrist", "l_hip", "r_hip",
                  "l_knee", "r_knee", "l_ankle", "r_ankle"]

    def __init__(self, yolo_model="yolov8n-pose.pt"):
        self.yolo = YOLO(yolo_model) if HAS_YOLO else None
        self.mp_pose = None
        if HAS_MEDIAPIPE:
            try:
                self.mp_pose = mp.solutions.pose.Pose(
                    static_image_mode=True, model_complexity=2,
                    min_detection_confidence=0.3)
            except (AttributeError, Exception) as e:
                print(f"[aviso] MediaPipe Pose no disponible ({e}); "
                      f"se sigue solo con YOLO-Pose.")
                self.mp_pose = None

    def _detect_yolo(self, img_bgr, conf):
        if self.yolo is None:
            return []
        people = []
        results = self.yolo(img_bgr, conf=conf, verbose=False)[0]
        if results.keypoints is None:
            return []
        for box, kpts in zip(results.boxes, results.keypoints):
            xyxy = box.xyxy[0].cpu().numpy().astype(int)
            kp = kpts.xy[0].cpu().numpy()
            kp_conf = kpts.conf[0].cpu().numpy() if kpts.conf is not None else np.ones(17)
            people.append({"bbox": xyxy, "keypoints": kp, "kp_conf": kp_conf, "z": None})
        return people

    def _refine_with_mediapipe(self, img_bgr, person):
        """Usa MediaPipe (dentro del bbox de la persona) para rellenar
        keypoints con confianza baja y obtener una z aproximada (profundidad)."""
        if self.mp_pose is None:
            return person
        x1, y1, x2, y2 = person["bbox"]
        x1, y1 = max(0, x1), max(0, y1)
        crop = img_bgr[y1:y2, x1:x2]
        if crop.size == 0:
            return person
        rgb = cv2.cvtColor(crop, cv2.COLOR_BGR2RGB)
        res = self.mp_pose.process(rgb)
        if not res.pose_landmarks:
            return person

        h, w = crop.shape[:2]
        lm = res.pose_landmarks.landmark
        # Mapeo aproximado MediaPipe(33) -> COCO(17)
        mp_map = {0: 0, 2: 1, 5: 2, 7: 3, 8: 4, 11: 5, 12: 6, 13: 7, 14: 8,
                  15: 9, 16: 10, 23: 11, 24: 12, 25: 13, 26: 14, 27: 15, 28: 16}

        z_vals = np.zeros(17)
        for coco_idx, mp_idx in mp_map.items():
            p = lm[mp_idx]
            visible = p.visibility if hasattr(p, "visibility") else 1.0
            z_vals[coco_idx] = p.z
            if person["kp_conf"][coco_idx] < 0.3 and visible > 0.4:
                person["keypoints"][coco_idx] = [x1 + p.x * w, y1 + p.y * h]
                person["kp_conf"][coco_idx] = visible
        person["z"] = z_vals
        return person

    def detect(self, img_bgr, conf=0.30):
        """Detección con reintento multi-escala: si YOLO no encuentra a nadie
        (persona muy pequeña o muy grande / recortada), se reescala la imagen."""
        people = self._detect_yolo(img_bgr, conf)

        if not people:
            for scale in (1.5, 2.0, 0.6):
                h, w = img_bgr.shape[:2]
                resized = cv2.resize(img_bgr, (int(w * scale), int(h * scale)))
                cand = self._detect_yolo(resized, conf * 0.85)
                if cand:
                    for p in cand:
                        p["bbox"] = (p["bbox"] / scale).astype(int)
                        p["keypoints"] = p["keypoints"] / scale
                    people = cand
                    break

        if HAS_MEDIAPIPE:
            people = [self._refine_with_mediapipe(img_bgr, p) for p in people]

        return people


