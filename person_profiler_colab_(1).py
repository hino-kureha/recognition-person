def _closest_label(rgb, table):
    rgb = np.array(rgb, dtype=float)
    best, best_d = None, float("inf")
    for name, ref in table.items():
        d = np.linalg.norm(rgb - np.array(ref, dtype=float))
        if d < best_d:
            best, best_d = name, d
    return best


def dominant_color(pixels_rgb, k=3):
    """pixels_rgb: array Nx3. Devuelve el color dominante (ignora outliers)."""
    if pixels_rgb is None or len(pixels_rgb) < k:
        return None
    km = KMeans(n_clusters=min(k, len(pixels_rgb)), n_init=4, random_state=0)
    labels = km.fit_predict(pixels_rgb)
    counts = np.bincount(labels)
    return km.cluster_centers_[np.argmax(counts)]


